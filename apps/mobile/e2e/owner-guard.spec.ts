import { test, expect } from '@playwright/test';

test('owner drafts guard exits, restore focus, and recover failed saves', async ({ page, context }, info) => {
  const ports = new Set((process.env.E2E_ALLOWED_PORTS || '').split(','));
  await context.route('**/*', async route => {
    const url = new URL(route.request().url());
    if (url.protocol === 'data:' || (url.hostname === '127.0.0.1' && ports.has(url.port))) await route.continue();
    else await route.abort('blockedbyclient');
  });
  await page.goto('/', { waitUntil: 'commit' });
  await page.locator('button[aria-label="Sign in"]').click();
  await page.getByRole('button', { name: 'New here? Create a free account' }).click();
  await page.getByPlaceholder('you@example.com').fill(`q29-${info.project.name}@example.test`);
  await page.getByPlaceholder('At least 12 characters').fill('synthetic-test-password-123');
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await page.getByRole('button', { name: 'Account', exact: true }).click();
  await page.getByRole('button', { name: 'My rental adverts' }).click();
  const name = page.getByLabel('PUBLIC NAME');
  await name.fill('Profile change');
  await page.keyboard.press('Escape');
  await expect(page.getByText('Discard unsaved changes?')).toBeVisible();
  await page.getByRole('button', { name: 'Keep editing' }).click();
  await expect(name).toHaveValue('Profile change');
  await expect(name).toBeFocused();
  await page.getByRole('button', { name: 'Messages', exact: true }).click();
  await page.getByRole('button', { name: 'Discard changes' }).click();
  await page.getByRole('button', { name: 'My adverts', exact: true }).click();
  await expect(name).toHaveValue('');
  await name.fill('Test owner');
  await page.getByRole('button', { name: 'Save profile' }).click();
  await page.getByRole('button', { name: /Test owner · Edit profile/ }).click();
  await name.fill('Updated owner');
  await page.getByRole('button', { name: /Test owner · Edit profile/ }).click();
  await page.getByRole('button', { name: 'Save and leave' }).click();
  await page.getByRole('button', { name: /Updated owner · Edit profile/ }).click();
  await expect(name).toHaveValue('Updated owner');
  await name.fill('Discard this profile');
  await page.getByRole('button', { name: 'Create rental advert' }).click();
  await page.getByRole('button', { name: 'Discard changes' }).click();
  await page.getByRole('button', { name: 'Back to adverts' }).click();
  await page.getByRole('button', { name: /Updated owner · Edit profile/ }).click();
  await expect(name).toHaveValue('Updated owner');
  await page.getByRole('button', { name: 'Create rental advert' }).click();
  const title = page.getByLabel('TITLE', { exact: true });
  await title.fill('Partial title');
  await page.getByRole('button', { name: 'Back to adverts' }).click();
  await expect(page.getByText('Discard unsaved changes?')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Save and leave' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Keep editing' }).click();
  await expect(title).toHaveValue('Partial title');
  await expect(title).toBeFocused();
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await expect(page.getByText('Discard unsaved changes?')).toBeVisible();
  await page.getByRole('button', { name: 'Keep editing' }).click();
  await expect(title).toBeFocused();
  await page.getByLabel('DESCRIPTION', { exact: true }).fill('A synthetic listing with enough detail for a valid draft.');
  await page.getByLabel('STREET AND BUILDING').fill('Testowa 29');
  await page.getByLabel('Location latitude').fill('50.06');
  await page.getByLabel('Location longitude').fill('19.94');
  let attempts = 0;
  await page.route(`${process.env.E2E_API_URL}/v1/me/adverts`, async route => {
    if (route.request().method() === 'POST' && ++attempts === 1) return route.fulfill({ status: 503, json: { detail: 'synthetic outage' } });
    return route.continue();
  });
  await page.getByRole('button', { name: 'Messages', exact: true }).click();
  await page.getByRole('button', { name: 'Save and leave' }).click();
  await expect(page.getByRole('alert').filter({ hasText: /Cannot reach the service/ })).toBeVisible();
  await expect(page.getByText('Discard unsaved changes?')).toBeVisible();
  await page.getByRole('button', { name: 'Keep editing' }).click();
  await expect(title).toHaveValue('Partial title');
  await page.getByRole('button', { name: 'Messages', exact: true }).click();
  await page.getByRole('button', { name: 'Save and leave' }).click();
  await expect(page.getByText('No conversations yet.')).toBeVisible();
  await page.getByRole('button', { name: 'My adverts', exact: true }).click();
  await expect(page.getByText('Partial title', { exact: true })).toBeVisible();
  expect(attempts).toBe(2);
  await page.getByRole('button', { name: 'Edit', exact: true }).click();
  await title.fill('Private unsaved canary');
  await page.route(`${process.env.E2E_API_URL}/v1/me/favorites`, route => route.fulfill({ status: 401, json: { detail: 'expired' } }));
  await page.route(`${process.env.E2E_AUTH_URL}/v1/auth/refresh`, route => route.fulfill({ status: 401, json: { detail: 'expired' } }));
  await expect(page.getByLabel('TITLE', { exact: true })).toHaveCount(0, { timeout: 25_000 });
  await expect(page.getByText('Discard unsaved changes?')).toHaveCount(0);
});
