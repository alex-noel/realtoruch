import { test, expect } from '@playwright/test';

test('message drafts survive thread switches and require discard to close', async ({ page, context }, info) => {
  test.setTimeout(60_000);
  const ports = new Set((process.env.E2E_ALLOWED_PORTS || '').split(','));
  await context.route('**/*', route => { const url = new URL(route.request().url()); return url.protocol === 'data:' || (url.hostname === '127.0.0.1' && ports.has(url.port)) ? route.continue() : route.abort(); });
  await page.goto('/', { waitUntil: 'commit' });
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.getByRole('button', { name: 'New here? Create a free account' }).click();
  await page.getByLabel('EMAIL', { exact: true }).fill(`q37-${info.project.name}@example.test`);
  await page.getByLabel('PASSWORD', { exact: true }).fill('synthetic-test-password-123');
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  const api = process.env.E2E_API_URL!, auth = process.env.E2E_AUTH_URL!;
  await page.route(`${api}/v1/me/conversations`, route => route.fulfill({ json: { items: [
    { id: 'a', title: 'Home A', listing_id: 'home-a', updated_at: '2026-01-01T00:00:00Z', unread_count: 0, blocked: false, can_unblock: false },
    { id: 'b', title: 'Home B', listing_id: null, updated_at: '2026-01-01T00:00:00Z', unread_count: 0, blocked: false, can_unblock: false },
  ], next_cursor: null } }));
  await page.route(`${api}/v1/me/conversations/*`, route => route.fulfill({ json: { id: route.request().url().split('/').at(-1), items: [], next_cursor: null, blocked: false, can_unblock: false } }));
  await page.getByRole('button', { name: 'Account', exact: true }).click();
  await page.getByRole('button', { name: 'Messages', exact: true }).click();
  const desk = page.getByRole('dialog', { name: 'Your rental desk.' });
  const composer = desk.getByLabel('YOUR MESSAGE');
  await desk.getByRole('button', { name: 'Open conversation: Home A' }).click();
  await composer.fill('Private draft A');
  await expect(desk.getByText('Unsent drafts stay here only while this rental desk is open.')).toBeVisible();
  let release!: () => void; const pending = new Promise<void>(resolve => { release = resolve; });
  const ids: string[] = [];
  await page.route(`${api}/v1/me/conversations/a/messages`, async route => {
    ids.push(route.request().postDataJSON().client_id);
    if (ids.length === 1) await pending;
    return route.fulfill({ status: 503, json: { detail: 'offline' } });
  });
  await desk.getByRole('button', { name: 'Send message', exact: true }).click();
  await desk.getByRole('button', { name: 'Close dialog' }).click();
  await expect(desk.getByText('Wait for the message to finish sending before leaving.')).toBeVisible();
  release();
  await expect(desk.getByText(/draft stays here while this rental desk is open/)).toBeVisible();
  await expect(desk.getByText('Wait for the message to finish sending before leaving.')).toHaveCount(0);
  await desk.getByRole('button', { name: 'Retry send' }).click();
  await expect.poll(() => ids.length).toBe(2);
  expect(ids[0]).toBe(ids[1]);
  await desk.getByRole('button', { name: 'All conversations' }).click();
  await desk.getByRole('button', { name: 'Open conversation: Home B' }).click();
  await composer.fill('Private draft B');
  await desk.getByRole('button', { name: 'All conversations' }).click();
  await desk.getByRole('button', { name: 'View home', exact: true }).click();
  await expect(desk.getByText(/Unsent message drafts stay only/)).toBeVisible();
  await desk.getByRole('button', { name: 'Keep editing' }).click();
  await desk.getByRole('button', { name: 'Open conversation: Home A' }).click();
  await expect(composer).toHaveValue('Private draft A');
  await expect(desk.getByRole('button', { name: 'Send message', exact: true })).toBeEnabled();
  await desk.getByRole('button', { name: 'My adverts', exact: true }).click();
  await desk.getByLabel('PUBLIC NAME').fill('Private profile edit');
  await desk.getByRole('button', { name: 'Close dialog' }).click();
  await expect(desk.getByText(/Unsent message drafts stay only/)).toBeVisible();
  await expect(desk.getByRole('button', { name: 'Save and leave' })).toHaveCount(0);
  await desk.getByRole('button', { name: 'Keep editing' }).click();
  await desk.getByRole('button', { name: 'Messages', exact: true }).click();
  await desk.getByRole('button', { name: 'Discard changes' }).click();
  await expect(composer).toHaveValue('Private draft A');
  await composer.focus();
  await page.keyboard.press('Escape');
  await expect(desk.getByText(/Unsent message drafts stay only/)).toBeVisible();
  await desk.getByRole('button', { name: 'Keep editing' }).click();
  await expect(composer).toHaveValue('Private draft A');
  await expect(composer).toBeFocused();
  await desk.getByRole('button', { name: 'Close dialog' }).click();
  await desk.getByRole('button', { name: 'Discard changes' }).click();
  await expect(desk).toHaveCount(0);
  await page.getByRole('button', { name: 'Account', exact: true }).click();
  await page.getByRole('button', { name: 'Messages', exact: true }).click();
  await desk.getByRole('button', { name: 'Open conversation: Home B' }).click();
  await expect(composer).toHaveValue('');
  await composer.fill('Must clear on account expiry');
  await desk.getByRole('button', { name: 'Close dialog' }).click();
  await expect(desk.getByText(/Unsent message drafts stay only/)).toBeVisible();
  await page.route(`${api}/v1/me/favorites`, route => route.fulfill({ status: 401, json: { detail: 'expired' } }));
  await page.route(`${auth}/v1/auth/refresh`, route => route.fulfill({ status: 401, json: { detail: 'expired' } }));
  await expect(desk).toHaveCount(0, { timeout: 25_000 });
  await expect(page.getByText('Must clear on account expiry')).toHaveCount(0);
});
