import { expect, test } from '@playwright/test';

test('unverified owner reviews a saved draft without publishing', async ({ page, context }, info) => {
  const ports = new Set((process.env.E2E_ALLOWED_PORTS || '').split(','));
  await context.route('**/*', route => { const url = new URL(route.request().url()); return url.protocol === 'data:' || (url.hostname === '127.0.0.1' && ports.has(url.port)) ? route.continue() : route.abort(); });
  await page.goto('/', { waitUntil: 'commit' });
  await page.locator('button[aria-label="Sign in"]').click();
  await page.getByRole('button', { name: 'New here? Create a free account' }).click();
  await page.getByPlaceholder('you@example.com').fill(`q31-${info.project.name}@example.test`);
  await page.getByPlaceholder('At least 12 characters').fill('synthetic-test-password-123');
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await page.getByRole('button', { name: 'Account', exact: true }).click();
  await page.getByRole('button', { name: 'My rental adverts' }).click();
  await page.getByLabel('PUBLIC NAME').fill('Preview owner');
  await page.getByRole('button', { name: 'Save profile' }).click();
  await page.getByRole('button', { name: 'Create rental advert' }).click();
  await page.getByLabel('TITLE', { exact: true }).fill('Preview synthetic rental');
  await page.getByLabel('DESCRIPTION', { exact: true }).fill('A synthetic listing used for preview verification.');
  await page.getByLabel('STREET AND BUILDING').fill('Testowa 31');
  await page.getByLabel('Location latitude').fill('50.06');
  await page.getByLabel('Location longitude').fill('19.94');
  await page.getByLabel('PHOTO LINKS (HTTPS; ONE PER LINE)').fill('https://example.test/photo.jpg');
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  let publishCalls = 0;
  await page.route(`${process.env.E2E_API_URL}/v1/me/adverts/*/publish`, route => { publishCalls++; return route.continue(); });
  await page.getByRole('button', { name: 'Review and publish', exact: true }).click();
  await expect(page.getByText('Review this rental')).toBeVisible();
  await expect(page.getByText(/Monthly rent and fees: Not stated; fees are unknown/)).toBeVisible();
  await expect(page.getByText(/Testowa 31/)).toBeVisible();
  await expect(page.getByText(/https:\/\/example.test\/photo.jpg/)).toBeVisible();
  await expect(page.getByText(/Verify your email in Account/)).toBeVisible();
  await expect(page.getByRole('button', { name: 'Publish advert' })).toBeDisabled();
  expect(publishCalls).toBe(0);
  await page.getByRole('button', { name: 'Edit draft' }).click();
  await expect(page.getByLabel('TITLE', { exact: true })).toHaveValue('Preview synthetic rental');
  await expect(page.getByLabel('PHOTO LINKS (HTTPS; ONE PER LINE)')).toHaveValue('https://example.test/photo.jpg');
  await page.getByRole('button', { name: 'Back to adverts' }).click();
  await page.getByRole('button', { name: 'Review and publish' }).click();
  await expect(page.getByText('Preview synthetic rental', { exact: true })).toBeVisible();
  expect(publishCalls).toBe(0);
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await page.getByRole('button', { name: 'Account', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Send verification email' })).toBeVisible();
  await page.getByRole('button', { name: 'My rental adverts' }).click();
  await expect(page.getByText('Preview synthetic rental', { exact: true })).toBeVisible();
});
